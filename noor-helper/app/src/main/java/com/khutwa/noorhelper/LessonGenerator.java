package com.khutwa.noorhelper;

import java.util.List;

final class LessonGenerator {
    private LessonGenerator() {}

    static LessonPreparation generate(String title, List<String> outcomes) {
        String safeTitle = title == null || title.trim().isEmpty() ? "الدرس المحدد" : title.trim();
        if (safeTitle.contains("الأنواع المختلفة من الأعداد")) {
            return numberTypes(safeTitle);
        }
        return genericMath(safeTitle, outcomes);
    }

    private static LessonPreparation numberTypes(String title) {
        String concepts = "الأعداد الطبيعية، الأعداد الصحيحة، الأعداد النسبية، الأعداد غير النسبية، "
                + "الأعداد الحقيقية، التمثيل على خط الأعداد، الانتماء والاحتواء بين مجموعات الأعداد.";

        String intro = "يعرض المعلم الأعداد: -3، 0، 1/2، √2، π، ويطلب من الطلبة تصنيف ما يعرفونه منها. "
                + "تتم مراجعة سريعة لمفهومي الأعداد الصحيحة والكسور، ثم يطرح سؤالًا محفزًا: هل كل عدد عشري يمكن كتابته على صورة كسر؟";

        String procedures = "1. يناقش المعلم مع الطلبة مجموعات الأعداد ويُبنى مخطط يوضح العلاقة بينها.\n"
                + "2. يعمل الطلبة في مجموعات لتصنيف بطاقات أعداد إلى طبيعية وصحيحة ونسبية وغير نسبية وحقيقية مع تبرير الاختيار.\n"
                + "3. يمثل الطلبة أمثلة مختارة على خط الأعداد ويقارنون بين العدد النسبي وغير النسبي.\n"
                + "4. تُعرض مواقف حياتية تتضمن قياسات وكسورًا وجذورًا ويحدد الطلبة نوع العدد المناسب لكل موقف.\n"
                + "5. يقدّم المعلم دعمًا بأمثلة أبسط للطلبة الذين يحتاجون مساندة، ومسائل تحدٍ تتطلب أكثر من تصنيف للطلبة المتقدمين.\n"
                + "6. يشرح عدد من الطلبة طريقة تفكيرهم ويصحح الصف التصنيفات غير الدقيقة بالحجة الرياضية.";

        String formative = "أسئلة شفهية سريعة أثناء الشرح، وتصنيف أعداد على بطاقات/سبورات صغيرة، "
                + "وتحليل خطأ في تصنيف عدد مع ذكر السبب، ثم سؤال تحقق قبل الانتقال لكل مفهوم جديد.";

        String summative = "تقويم ختامي قصير: 1) صنّف -5. 2) صنّف 3/4. 3) صنّف √3 مع التعليل. "
                + "4) مثّل عددًا نسبيًا وعددًا غير نسبي تقريبًا على خط الأعداد. "
                + "5) اختر نوع العدد الأنسب لموقف غير مألوف وفسّر اختيارك.";

        String weekly = "تعرّف الطلبة إلى الأنواع المختلفة من الأعداد الحقيقية والتمييز بين الأعداد النسبية وغير النسبية. "
                + "يرجى مراجعة أمثلة الدرس وحل التدريبات المحددة من الكتاب.";

        return new LessonPreparation(title, concepts, intro, procedures, formative, summative, weekly);
    }

    private static LessonPreparation genericMath(String title, List<String> outcomes) {
        String objectiveHint = outcomes == null || outcomes.isEmpty()
                ? "المخرجات التعليمية المرتبطة بالدرس"
                : "المخرجات التعليمية المحددة في نور";
        String concepts = "المفاهيم والمصطلحات الرئيسة المرتبطة بدرس «" + title + "»، مع ربطها بالتمثيلات الرياضية المناسبة.";
        String intro = "مراجعة سريعة للتعلم القبلي المرتبط بالدرس، ثم عرض موقف قصير أو سؤال تشخيصي يكشف أفكار الطلبة السابقة ويمهد لمفهوم الدرس.";
        String procedures = "1. استكشاف الفكرة الرئيسة من خلال مثال موجه.\n"
                + "2. نشاط تعاوني قصير يطبق فيه الطلبة المفهوم ويبررون خطواتهم.\n"
                + "3. مناقشة الحلول وتصحيح التصورات غير الدقيقة.\n"
                + "4. تطبيق متدرج من المباشر إلى موقف غير مألوف، مع دعم للمتعثرين وتحدٍ للمتقدمين.\n"
                + "5. تلخيص العلاقة بين الأمثلة و" + objectiveHint + ".";
        String formative = "أسئلة تحقق قصيرة، ملاحظة أداء المجموعات، سؤال تحليل خطأ، واستجابة فردية سريعة أثناء سير الدرس.";
        String summative = "تقويم قصير يتضمن سؤال فهم، سؤال تطبيق، سؤال تبرير أو تحليل، ومسألة سياقية مرتبطة بمفهوم الدرس.";
        String weekly = "تم تناول درس «" + title + "». يرجى مراجعة أمثلة الدرس والمفاهيم الرئيسة وحل التدريبات المحددة من الكتاب.";
        return new LessonPreparation(title, concepts, intro, procedures, formative, summative, weekly);
    }
}
