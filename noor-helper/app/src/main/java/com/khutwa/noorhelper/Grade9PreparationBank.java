    private Grade9PreparationBank() {}

    static LessonPreparation get(String noorTitle) {
        Grade9Curriculum.Lesson lesson = Grade9Curriculum.find(noorTitle);
        if (lesson == null) return null;
        Spec s = SPECS.get(lesson.code);
        if (s == null) return null;

        String objectives = joinObjectives(lesson);
        String pages = exercisePages(noorTitle);

        String procedures =
                "1. يوضح المعلم هدف الدرس بلغة مبسطة ويربطه بالتعلم القبلي: " + s.prior + "\n"
                + "2. يقدم مثالًا موجّهًا من نفس فكرة ورقة «خطواتي نحو التميز»، مع مناقشة خطوات التفكير لا حفظ القاعدة فقط.\n"
                + "3. نشاط تعلم نشط: " + s.activity + "\n"
                + "4. ينفذ الطلبة تمارين الدرس المرفقة من ملف «خطواتي نحو التميز» (" + pages + ")، مع مناقشة الحلول وتصحيح الأخطاء الشائعة.\n"
                + "5. تمايز: يقدم للمتعثرين مثالًا جزئيًا وخطوات مساعدة، ويعطى المتقدمون مسألة توسع تتطلب تفسيرًا أو تعميمًا.\n"
                + "6. سؤال تفكير أعلى: " + s.higher + "\n"
                + "7. يغلق المعلم الدرس بربط ما تم تنفيذه بالمخرج الرسمي: " + objectives;

        String formative =
                "ملاحظة أداء الطلبة أثناء النشاط وتمارين الورقة، سؤال شفهي بعد كل فكرة رئيسة، "
                + "استجابة فردية سريعة على السبورة/بطاقة، وتحليل خطأ قصير مرتبط بالهدف الرسمي.";

        String summative =
                s.finalCheck + " يطلب من الطالب إظهار الخطوات أو تبرير الاختيار بما يناسب طبيعة السؤال.";

        String weekly =
                "تم تنفيذ درس «" + lesson.title + "» وفق الخطة الفصلية الرسمية. "
                + "يرجى مراجعة أمثلة وتمارين الدرس في ملف «خطواتي نحو التميز» (" + pages + ").";

        return new LessonPreparation(noorTitle, s.concepts, s.prior, procedures, formative, summative, weekly);
    }

    private static String joinObjectives(Grade9Curriculum.Lesson lesson) {
        StringBuilder b = new StringBuilder();
        for (int i=0;i<lesson.objectives.size();i++) {
            if (i>0) b.append(" / ");
            b.append(lesson.objectives.get(i));
        }
        return b.toString();
    }

    private static String exercisePages(String noorTitle) {
        ExerciseMap.Lesson ex = ExerciseMap.find(noorTitle);
        if (ex == null || ex.segments == null || ex.segments.length == 0) return "الصفحات المرتبطة بالدرس";
        StringBuilder b = new StringBuilder("PDF ");
        for (int i=0;i<ex.segments.length;i++) {
            if (i>0) b.append("، ");
            ExerciseMap.Segment s = ex.segments[i];
            b.append("ص").append(s.pdfPage);
            if (s.side == ExerciseMap.Side.RIGHT) b.append(" - الجزء الأيمن");
            else if (s.side == ExerciseMap.Side.LEFT) b.append(" - الجزء الأيسر");
        }
        return b.toString();
    }

    private static void put(String code, String concepts, String prior, String activity, String higher, String finalCheck) {
        SPECS.put(code, new Spec(concepts, prior, activity, higher, finalCheck));
    }
