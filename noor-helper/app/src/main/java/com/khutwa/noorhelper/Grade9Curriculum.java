    private Grade9Curriculum() {}

    static Lesson find(String noorTitle) {
        ExerciseMap.Lesson mapped = ExerciseMap.find(noorTitle);
        return mapped == null ? null : LESSONS.get(mapped.code);
    }

    static Lesson byCode(String code) {
        return LESSONS.get(code);
    }

    static int lessonCount() {
        return LESSONS.size();
    }

    static List<Lesson> allLessons() {
        return new ArrayList<>(LESSONS.values());
    }

    static int indexOfCode(String code) {
        int i = 0;
        for (String key : LESSONS.keySet()) {
            if (key.equals(code)) return i;
            i++;
        }
        return -1;
    }

    static int totalPlannedLessonPeriods() {
        int total = 0;
        for (Lesson l : LESSONS.values()) total += l.periods;
        return total;
    }

    private static List<String> obj(String... items) {
        return Arrays.asList(items);
    }

    private static void add(String code, String title, String unit, int periods,
                            String start, String end, int weekStart, int weekEnd,
                            String level, List<String> objectives, List<String> strategies) {
        LESSONS.put(code, new Lesson(code, title, unit, periods, start, end, weekStart, weekEnd,
                level, objectives, strategies, RESOURCES));
    }
